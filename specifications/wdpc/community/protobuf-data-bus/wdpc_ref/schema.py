"""Build one compilable proto3 schema from the protobuf blocks in the WDPC spec.

Resolution rules (documented in METHODOLOGY.md):

1. Every message and enum the spec defines is kept with the exact field
   names, types and numbers the spec gives.
2. When a message is defined twice, the Annex A (normative) definition wins.
   In WDPC v1.0 this decides WorkloadDataPublication.future_intent = 7
   (Annex A) over = 16 (body text).
3. A definition the spec leaves truncated keeps only its complete fields.
4. Every type the spec references but never defines becomes an empty
   placeholder message. An empty message is wire compatible with any future
   definition: a v1 reader keeps the bytes as unknown fields.
5. Everything lives in one package, ``wdpc.v1``. Annex A names three
   packages but stops partway through the third, so splitting would leave
   dangling cross-package references.

The schema is emitted two ways from the same model: as .proto text (for
protoc and other languages) and as a FileDescriptorProto loaded at runtime,
so the Python package only needs the ``protobuf`` runtime.
"""

from __future__ import annotations

from functools import cache
from pathlib import Path

from google.protobuf import descriptor_pb2, descriptor_pool, message_factory, timestamp_pb2

from .specparse import Definition, SpecModel, lint_file

PACKAGE = "wdpc.v1"
FILE_NAME = "wdpc/v1/wdpc.proto"
HERE = Path(__file__).resolve().parent
SPEC_PATH = HERE.parent / "spec" / "WDPC-Spec.md"
PROTO_PATH = HERE.parent / "proto" / FILE_NAME

_SCALAR_TYPES = {
    "double": descriptor_pb2.FieldDescriptorProto.TYPE_DOUBLE,
    "float": descriptor_pb2.FieldDescriptorProto.TYPE_FLOAT,
    "int32": descriptor_pb2.FieldDescriptorProto.TYPE_INT32,
    "int64": descriptor_pb2.FieldDescriptorProto.TYPE_INT64,
    "uint32": descriptor_pb2.FieldDescriptorProto.TYPE_UINT32,
    "uint64": descriptor_pb2.FieldDescriptorProto.TYPE_UINT64,
    "sint32": descriptor_pb2.FieldDescriptorProto.TYPE_SINT32,
    "sint64": descriptor_pb2.FieldDescriptorProto.TYPE_SINT64,
    "fixed32": descriptor_pb2.FieldDescriptorProto.TYPE_FIXED32,
    "fixed64": descriptor_pb2.FieldDescriptorProto.TYPE_FIXED64,
    "sfixed32": descriptor_pb2.FieldDescriptorProto.TYPE_SFIXED32,
    "sfixed64": descriptor_pb2.FieldDescriptorProto.TYPE_SFIXED64,
    "bool": descriptor_pb2.FieldDescriptorProto.TYPE_BOOL,
    "string": descriptor_pb2.FieldDescriptorProto.TYPE_STRING,
    "bytes": descriptor_pb2.FieldDescriptorProto.TYPE_BYTES,
}


def _is_annex(d: Definition) -> bool:
    return d.section.endswith(".proto")


def resolve(model: SpecModel) -> tuple[list[Definition], list[str]]:
    """Pick one definition per name and list placeholder types."""
    chosen: dict[str, Definition] = {}
    for name, group in model.by_name().items():
        annex = [d for d in group if _is_annex(d)]
        chosen[name] = annex[-1] if annex else group[-1]
    ordered = sorted(chosen.values(), key=lambda d: (d.block, d.line))
    return ordered, model.undefined_types()


def to_proto_text(model: SpecModel) -> str:
    defs, placeholders = resolve(model)
    out = [
        "// GENERATED by tools/build_schema.py from spec/WDPC-Spec.md. Do not edit by hand.",
        "// Field names, types and numbers are taken from the WDPC v1.0 specification.",
        "// See METHODOLOGY.md for how duplicate, truncated and undefined types were resolved.",
        'syntax = "proto3";',
        "",
        f"package {PACKAGE};",
        "",
        'import "google/protobuf/timestamp.proto";',
        "",
    ]
    for d in defs:
        note = "Annex A" if _is_annex(d) else "body"
        trunc = "" if d.closed else " (truncated in the spec; only complete fields kept)"
        out.append(f"// From spec line {d.line}, section \"{d.section}\" ({note}){trunc}.")
        out.append(f"{d.kind} {d.name} {{")
        if d.kind == "enum":
            for n, v in d.values:
                out.append(f"  {n} = {v};")
        else:
            for f in d.fields:
                if f.map_key is not None:
                    out.append(f"  map<{f.map_key}, {f.map_value}> {f.name} = {f.number};")
                else:
                    rep = "repeated " if f.repeated else ""
                    out.append(f"  {rep}{f.type} {f.name} = {f.number};")
        out.append("}")
        out.append("")
    out.append("// ---- Placeholders: referenced by the spec but not defined in WDPC v1.0 ----")
    for name in placeholders:
        out.append(f"message {name} {{}}")
    out.append("")
    return "\n".join(out)


def to_file_descriptor(model: SpecModel) -> descriptor_pb2.FileDescriptorProto:
    defs, placeholders = resolve(model)
    fdp = descriptor_pb2.FileDescriptorProto(
        name=FILE_NAME, package=PACKAGE, syntax="proto3",
        dependency=["google/protobuf/timestamp.proto"])
    FD = descriptor_pb2.FieldDescriptorProto

    def set_type(fp: FD, t: str) -> None:
        if t in _SCALAR_TYPES:
            fp.type = _SCALAR_TYPES[t]
        elif t.startswith("google."):
            fp.type = FD.TYPE_MESSAGE
            fp.type_name = "." + t
        elif t in enums:
            fp.type = FD.TYPE_ENUM
            fp.type_name = f".{PACKAGE}.{t}"
        else:
            fp.type = FD.TYPE_MESSAGE
            fp.type_name = f".{PACKAGE}.{t}"

    enums = {d.name for d in defs if d.kind == "enum"}
    for d in defs:
        if d.kind == "enum":
            e = fdp.enum_type.add(name=d.name)
            for n, v in d.values:
                e.value.add(name=n, number=v)
            continue
        m = fdp.message_type.add(name=d.name)
        for f in d.fields:
            fp = m.field.add(name=f.name, number=f.number, json_name=_camel(f.name))
            if f.map_key is not None:
                entry_name = _camel(f.name, upper=True) + "Entry"
                entry = m.nested_type.add(name=entry_name)
                entry.options.map_entry = True
                k = entry.field.add(name="key", number=1, label=FD.LABEL_OPTIONAL, json_name="key")
                set_type(k, f.map_key)
                v = entry.field.add(name="value", number=2, label=FD.LABEL_OPTIONAL,
                                    json_name="value")
                set_type(v, f.map_value)
                fp.label = FD.LABEL_REPEATED
                fp.type = FD.TYPE_MESSAGE
                fp.type_name = f".{PACKAGE}.{d.name}.{entry_name}"
            else:
                fp.label = FD.LABEL_REPEATED if f.repeated else FD.LABEL_OPTIONAL
                set_type(fp, f.type)
    for name in placeholders:
        fdp.message_type.add(name=name)
    return fdp


def _camel(name: str, upper: bool = False) -> str:
    parts = name.split("_")
    s = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return s[:1].upper() + s[1:] if upper else s


@cache
def load(spec_path: str | None = None):
    """Return a namespace of message classes built from the spec."""
    model = lint_file(spec_path or SPEC_PATH)
    pool = descriptor_pool.DescriptorPool()
    pool.AddSerializedFile(timestamp_pb2.DESCRIPTOR.serialized_pb)
    fd = pool.Add(to_file_descriptor(model))
    classes = {name: message_factory.GetMessageClass(desc)
               for name, desc in fd.message_types_by_name.items()}
    enums = {name: desc for name, desc in fd.enum_types_by_name.items()}
    return _Namespace(classes, enums, fd)


class _Namespace:
    def __init__(self, classes, enums, file_descriptor):
        self._classes = classes
        self.enums = enums
        self.file_descriptor = file_descriptor

    def __getattr__(self, name):
        try:
            return self._classes[name]
        except KeyError:
            raise AttributeError(name) from None

    def names(self) -> list[str]:
        return sorted(self._classes)

    def enum_value(self, enum: str, name: str) -> int:
        return self.enums[enum].values_by_name[name].number
